export function getIndustryBySlug(slug: string) {
  return industries.find(i => i.slug === slug);
}

export function getLocationBySlug(slug: string) {
  return locations.find(l => l.slug === slug);
}

export function getCountries() {
  const unique = new Set(locations.map(l => l.country));
  return Array.from(unique).map(country => ({
    slug: country.toLowerCase().replace(/\s+/g, '-'),
    name: country
  }));
}

export function getCitiesByCountry(countrySlug: string) {
  return locations.filter(l => l.country.toLowerCase().replace(/\s+/g, '-') === countrySlug);
}

export function getAllCombinations() {
  const combinations: { industry: string; city: string }[] = [];
  for (const industry of industries) {
    for (const location of locations) {
      combinations.push({
        industry: industry.slug,
        city: location.slug
      });
    }
  }
  return combinations;
}

export function getSitemapChunks(chunkSize = 10000) {
  const all = getAllCombinations();
  const chunks = [];
  for (let i = 0; i < all.length; i += chunkSize) {
    chunks.push(all.slice(i, i + chunkSize));
  }
  return chunks;
}
